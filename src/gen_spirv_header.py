#!/usr/bin/env python3
"""Generate a C++ header embedding SPIR-V binaries as uint32_t arrays.

Usage: gen_spirv_header.py --out <header> [--hash-out <header>] <spv files...>

Symbol names are derived from the input filenames, so adding a shader
variant only requires adding its glslc rule to CMakeLists.txt (which
appends to VK_SPV_OUTPUTS, passed through as the input list here) —
this script never needs editing for new variants.

Mapping: <stem>.spv -> <stem>_spv / <stem>_spv_size, where <stem> is the
basename without extension with '-' replaced by '_'. The header order is
sorted by symbol for deterministic output. --hash-out writes a header
holding a content hash of every module plus one per filter family, which
names the runtime pipeline cache files. A family's hash only moves when a
module that family compiles changes, so editing one kernel starts a fresh
cache for that filter instead of cold-starting every filter.
"""

import argparse
import hashlib
import re
import sys
from pathlib import Path

_SYMBOL_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_SPV_MAGIC = 0x07230203


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def symbol_for(path: Path) -> str:
    stem = path.stem.replace("-", "_")
    if not _SYMBOL_RE.fullmatch(stem):
        fail(f"cannot derive a C identifier from {path.name!r}")
    return stem


def read_spv(path: Path) -> bytes:
    """Read one module and reject anything that is not a whole SPIR-V binary."""
    data = path.read_bytes()
    if len(data) == 0 or len(data) % 4 != 0:
        fail(f"{path}: size {len(data)} is not a positive multiple of 4 bytes")
    magic = int.from_bytes(data[:4], "little")
    if magic != _SPV_MAGIC:
        fail(f"{path}: not SPIR-V (magic 0x{magic:08x}, expected 0x{_SPV_MAGIC:08x})")
    return data


def emit_spv(f, name: str, data: bytes) -> None:
    f.write(f"static const uint32_t {name}_spv[] = {{\n    ")
    for i in range(0, len(data), 4):
        value = int.from_bytes(data[i : i + 4], "little")
        f.write(f"0x{value:08x}u, ")
        if (i // 4 + 1) % 8 == 0:
            f.write("\n    ")
    f.write("\n};\n")
    f.write(f"static const size_t {name}_spv_size = sizeof({name}_spv);\n\n")


def content_hash(modules: list[tuple[str, bytes]]) -> str:
    """A stable digest of every module, safe to put in a filename."""
    digest = hashlib.sha256()
    for sym, data in sorted(modules, key=lambda item: item[0]):
        digest.update(sym.encode("utf-8"))
        digest.update(b"\0")
        digest.update(len(data).to_bytes(8, "little"))
        digest.update(data)
    return digest.hexdigest()[:16]


def family_for(symbol: str) -> str:
    """The leading alphanumeric run, mirroring the host's family rule."""
    family = ""
    for char in symbol:
        if not (char.isascii() and char.isalnum()):
            break
        family += char.lower()
    return family[:32] or "misc"


def family_hashes(modules: list[tuple[str, bytes]]) -> dict[str, str]:
    """One digest per family; a module only moves its own family's hash."""
    groups: dict[str, list[tuple[str, bytes]]] = {}
    for module in modules:
        groups.setdefault(family_for(module[0]), []).append(module)
    return {family: content_hash(group) for family, group in groups.items()}


def emit_hash(path: Path, value: str, families: dict[str, str]) -> None:
    lines = [
        "// Generated by gen_spirv_header.py - do not edit",
        "",
        "#pragma once",
        "",
        "#include <cstring>",
        "",
        f'#define VSFEEL_SPIRV_HASH "{value}"',
        "",
        "// One hash per filter family, keyed by the leading alphanumeric run of a",
        "// variant's output name. Editing one kernel only moves its own family's",
        "// cache file away.",
        "struct VsfeelSpirvFamilyHash {",
        "    const char * family;",
        "    const char * hash;",
        "};",
        "",
        "inline const char * vsfeel_spirv_hash_for_family(const char * family) {",
        "    static const VsfeelSpirvFamilyHash entries[] = {",
    ]
    for family in sorted(families):
        lines.append(f'        {{ "{family}", "{families[family]}" }},')
    lines += [
        "    };",
        "    for (const auto & entry : entries) {",
        "        if (std::strcmp(entry.family, family) == 0) {",
        "            return entry.hash;",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, help="output header path")
    parser.add_argument(
        "--hash-out",
        help="optional header holding the modules' content hash",
    )
    parser.add_argument("spv", nargs="+", help="input .spv files")
    args = parser.parse_args()

    inputs = [(symbol_for(Path(a)), Path(a)) for a in args.spv]
    seen: dict[str, str] = {}
    for sym, path in inputs:
        if sym in seen:
            fail(f"duplicate symbol {sym!r} from {seen[sym]} and {path}")
        seen[sym] = str(path)
    modules: list[tuple[str, bytes]] = []
    for sym, path in inputs:
        if not path.is_file():
            fail(f"missing input {path}")
        modules.append((sym, read_spv(path)))

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w") as f:
        f.write("// Generated by gen_spirv_header.py - do not edit\n\n")
        f.write("#pragma once\n\n")
        f.write("#include <cstddef>\n")
        f.write("#include <cstdint>\n\n")
        for sym, data in sorted(modules, key=lambda item: item[0]):
            emit_spv(f, sym, data)

    if args.hash_out:
        emit_hash(
            Path(args.hash_out),
            content_hash(modules),
            family_hashes(modules),
        )


if __name__ == "__main__":
    main()
